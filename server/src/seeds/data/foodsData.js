function r1(n) {
  return Math.round(n * 10) / 10;
}

/**
 * Tuple format:
 * [slug, name, category, kcal100, p100, c100, f100, fib100, unitMeasure, unitGrams, unitLabel, baseUnit?]
 */
function expandFoodTuple([
  slug,
  name,
  category,
  kcal100,
  p100,
  c100,
  f100,
  fib100,
  unitMeasure,
  unitGrams,
  unitLabel,
  baseUnit = 'g',
]) {
  const ratio = unitGrams / 100;
  const householdServing = {
    measure: unitMeasure,
    baseQuantity: 1,
    label: unitLabel,
    gramsEquivalent: unitGrams,
    calories: Math.round(kcal100 * ratio),
    protein: r1(p100 * ratio),
    carbs: r1(c100 * ratio),
    fat: r1(f100 * ratio),
    fiber: r1(fib100 * ratio),
  };

  const baseServing = {
    measure: baseUnit,
    baseQuantity: 100,
    label: `100 ${baseUnit}`,
    gramsEquivalent: 100,
    calories: Math.round(kcal100),
    protein: r1(p100),
    carbs: r1(c100),
    fat: r1(f100),
    fiber: r1(fib100),
  };

  const servings =
    unitMeasure === baseUnit
      ? [baseServing]
      : [householdServing, baseServing];

  return {
    slug,
    name,
    category,
    servings,
    defaultServingIndex: 0,
  };
}

